#!/usr/bin/env python3
"""Generate Unicode/UnicodeNames.cpp: character names for the blocks fonts typically cover.

Run from the repository root: python3 tools/gen_unicode_names.py
"""
import sys
import unicodedata

RANGES = [
    (0x0020, 0x058F),  # Latin, IPA, spacing modifiers, combining marks, Greek, Cyrillic, Armenian
    (0x1D00, 0x1FFF),  # Phonetic extensions, Latin Extended Additional, Greek Extended
    (0x2000, 0x2BFF),  # Punctuation, super/subscripts, currency, letterlike, arrows, math, shapes, symbols
    (0x2C60, 0x2C7F),  # Latin Extended-C
    (0x2E00, 0x2E7F),  # Supplemental punctuation
    (0xA720, 0xA7FF),  # Latin Extended-D
    (0xFB00, 0xFB4F),  # Alphabetic presentation forms (ligatures)
    (0xFFF0, 0xFFFF),  # Specials
]


def pretty(name):
    words = name.split(" ")
    small = "SMALL" in words
    out = [(w.lower() if small else w) if len(w) == 1 else w.lower() for w in words]
    out[0] = out[0][:1].upper() + out[0][1:]
    return " ".join(out)


def main():
    rows = []
    for first, last in RANGES:
        for cp in range(first, last + 1):
            name = unicodedata.name(chr(cp), "")
            if name:
                rows.append((cp, pretty(name)))
    with open("Unicode/UnicodeNames.cpp", "w") as f:
        f.write("// Generated by tools/gen_unicode_names.py "
                f"(Unicode {unicodedata.unidata_version}). Do not edit.\n\n")
        f.write('#include "UnicodeNames.hpp"\n\n#include <algorithm>\n#include <iterator>\n\n')
        f.write("namespace {\n\nstruct Entry {\n  char32_t    codePoint;\n  const char *name;\n};\n\n")
        f.write("const Entry ENTRIES[] = {\n")
        for cp, name in rows:
            f.write(f'    {{0x{cp:04X}, "{name}"}},\n')
        f.write("};\n\n} // namespace\n\n")
        f.write(
            "QString unicodeName(char32_t codePoint) {\n"
            "  auto it = std::lower_bound(std::begin(ENTRIES), std::end(ENTRIES), codePoint,\n"
            "                             [](const Entry &e, char32_t cp) { return e.codePoint < cp; });\n"
            "  if ((it != std::end(ENTRIES)) && (it->codePoint == codePoint)) return QString(it->name);\n"
            "  if ((codePoint >= 0xE000) && (codePoint <= 0xF8FF)) return QString(\"Private use\");\n"
            "  return QString();\n"
            "}\n")
    print(f"{len(rows)} names", file=sys.stderr)


if __name__ == "__main__":
    main()
